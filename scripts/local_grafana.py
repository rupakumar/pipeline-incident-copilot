"""Run the local Grafana: the copilot's ticket desk at http://localhost:3000.

Reads the incident store (data/runtime/copilot.db) read-only through the SQLite data source and shows the
Incident desk (filter by platform / application) + Ticket detail dashboards, whose Approve / Deny buttons open
the approval console (`copilot serve`), and the Connections dashboard (every connected platform and pipeline,
with "+ Connect a pipeline" opening the console's connect form). Dashboards are generated by
scripts/build_local_dashboards.py. Everything is provisioned from infra/grafana/local/; Grafana's own state lives in the
git-ignored data/runtime/grafana/. The pipeline-health dashboard stays on Grafana Cloud
(scripts/publish_grafana_dashboard.py).

Steps: install the SQLite plugin if missing → render the dashboards (fill in this machine's links) →
start Grafana in the foreground (Ctrl+C stops it).

Usage: python -m scripts.local_grafana [--render-only]
Needs: brew install grafana
"""

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

from pipeline_incident_copilot.config import PROJECT_ROOT, RUNTIME_DIR
from pipeline_incident_copilot.notifications.approval_links import DEFAULT_BASE_URL
from pipeline_incident_copilot.storage.database import DB_PATH

LOCAL = PROJECT_ROOT / "infra" / "grafana" / "local"
STATE = RUNTIME_DIR / "grafana"
PLUGIN = "frser-sqlite-datasource"
URL = "http://localhost:3000"


def grafana_binary() -> tuple[Path, Path]:
    """(grafana binary, its homepath with the web assets)."""
    found = shutil.which("grafana") or "/opt/homebrew/opt/grafana/bin/grafana"
    binary = Path(found).resolve()
    if not binary.exists():
        sys.exit("Grafana not found: brew install grafana")
    return binary, binary.parent.parent / "share" / "grafana"


def ensure_plugin(binary: Path, home: Path) -> None:
    plugins = STATE / "plugins"
    if (plugins / PLUGIN).exists():
        return
    plugins.mkdir(parents=True, exist_ok=True)
    print(f"installing the {PLUGIN} plugin …")
    subprocess.run(
        [str(binary), "cli", "--homepath", str(home), "--pluginsDir", str(plugins), "plugins", "install", PLUGIN],
        check=True,
    )


def langfuse_project_url() -> str:
    """The Langfuse project page (ticket links open its sessions); the base URL if the project can't be read."""
    base = os.getenv("LANGFUSE_BASE_URL", "https://cloud.langfuse.com").rstrip("/")
    try:
        from pipeline_incident_copilot.observability.langfuse_tracer import get_langfuse

        projects = get_langfuse().api.projects.get().data
        return f"{base}/project/{projects[0].id}" if projects else base
    except Exception:  # noqa: BLE001 — no keys or offline: links still open Langfuse
        return base


def render_dashboards() -> list[Path]:
    """Copy the dashboards into Grafana's state folder with this machine's links filled in."""
    values = {
        "__APPROVAL_CONSOLE_URL__": os.getenv("COPILOT_APPROVAL_BASE_URL", DEFAULT_BASE_URL).rstrip("/"),
        "__LANGFUSE_PROJECT_URL__": langfuse_project_url(),
        "__PIPELINE_HEALTH_URL__": (os.getenv("GRAFANA_URL") or "https://grafana.com").rstrip("/")
        + "/d/pipeline-health",
    }
    out = STATE / "dashboards"
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for source in sorted((LOCAL / "dashboards").glob("*.json")):
        text = source.read_text()
        for placeholder, value in values.items():
            text = text.replace(placeholder, value)
        (out / source.name).write_text(text)
        written.append(out / source.name)
    return written


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--render-only", action="store_true", help="update the dashboards of a running Grafana")
    args = parser.parse_args()

    binary, home = grafana_binary()
    ensure_plugin(binary, home)
    for path in render_dashboards():
        print(f"dashboard {path.name}")
    if args.render_only:
        print("rendered; a running Grafana picks them up within 10 s")
        return
    env = {
        **os.environ,
        "COPILOT_GRAFANA_DATA": str(STATE),
        "COPILOT_GRAFANA_PROVISIONING": str(LOCAL / "provisioning"),
        "COPILOT_DB_PATH": str(DB_PATH),
    }
    print(f"Incident desk: {URL}  (view without login; admin/admin to edit)   Ctrl+C stops Grafana")
    try:
        subprocess.run(
            [str(binary), "server", "--homepath", str(home), "--config", str(LOCAL / "grafana.ini")],
            env=env,
            check=False,
        )
    except KeyboardInterrupt:
        print("stopped")


if __name__ == "__main__":
    main()
